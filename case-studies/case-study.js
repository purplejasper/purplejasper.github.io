const bindLanguageSwitch = () => {
  const control = document.querySelector('[data-language-switch]');
  if (!control) return;
  let startX = null;
  let suppressClick = false;
  const choose = (nextLanguage) => {
    const normalized = nextLanguage === 'it' ? 'it' : 'en';
    if (normalized === language) return;
    try { window.localStorage.setItem('portfolio-language', normalized); } catch {}
    control.dataset.language = normalized;
    control.querySelectorAll('button[data-language]').forEach((button) => {
      button.setAttribute('aria-pressed', String(button.dataset.language === normalized));
    });
    document.documentElement.classList.add('language-changing');
    window.setTimeout(() => window.location.reload(), 340);
  };
  control.addEventListener('pointerdown', (event) => { startX = event.clientX; }, { passive: true });
  control.addEventListener('pointerup', (event) => {
    if (startX === null) return;
    const distance = event.clientX - startX;
    startX = null;
    if (Math.abs(distance) < 18) return;
    suppressClick = true;
    choose(distance > 0 ? 'en' : 'it');
    window.setTimeout(() => { suppressClick = false; }, 300);
  }, { passive: true });
  control.addEventListener('pointercancel', () => { startX = null; }, { passive: true });
  control.querySelectorAll('button').forEach((button) => button.addEventListener('click', () => {
    if (!suppressClick) choose(button.dataset.language);
  }));
};

